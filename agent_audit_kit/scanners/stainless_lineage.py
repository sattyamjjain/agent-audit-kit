"""Stainless-generator provenance / lineage detector.

Detects MCP-server / SDK source trees produced by Stainless
(stainless.com — the API-spec-to-SDK generator Anthropic acquired
on 2026-05-18; see
https://www.anthropic.com/news/anthropic-acquires-stainless).

This is a **provenance** rule, not a vulnerability rule. Severity
`INFO`. It surfaces the lineage of code in a target tree so:

  - Procurement teams can answer "which of our MCP servers / SDKs
    are generator-produced vs hand-authored?"
  - SBOM / supply-chain attestation work has a concrete data point
    on origin.
  - If a future CVE class lands against a specific Stainless
    generator version, the rule can be re-targeted to fire on the
    affected lineage.

It does NOT claim a vulnerability today — there is no public
disclosure of a default-posture risk in Stainless-generated code.
The Anthropic acquisition announcement (2026-05-18) makes no
mention of winding down the generator or of pre-vs-post-acquisition
default differences; AAK does not pretend to know either way.

Concrete detector patterns (verified against
github.com/anthropics/anthropic-sdk-python/main/src/anthropic/__init__.py
on 2026-05-19):

  1. Banner comment in a Python/TypeScript/etc. source file:
     `File generated from our OpenAPI spec by Stainless.`
  2. `.stainless` config directory or `stainless.yml` config file
     at the project root (standard Stainless config-as-code shape).
  3. A `# Code generated by Stainless` short-form banner in some
     subset of generator outputs.

Detector contract:
    scan(project_root) -> (list[Finding], set[str])
"""
from __future__ import annotations

import re
from pathlib import Path

from agent_audit_kit.models import Category, Finding, Severity


# Verified verbatim against anthropic-sdk-python `__init__.py`:
# `# File generated from our OpenAPI spec by Stainless. See CONTRIBUTING.md for details.`
_BANNER_RE = re.compile(
    r"(?i)(?:File generated from our OpenAPI spec by Stainless|Code generated by Stainless)",
)

_CONFIG_FILE_CANDIDATES: frozenset[str] = frozenset({
    "stainless.yml",
    "stainless.yaml",
    "stainless.config.json",
    ".stainless.yml",
    ".stainless.yaml",
})
_CONFIG_DIR_CANDIDATES: frozenset[str] = frozenset({".stainless", "stainless"})

# Source-file suffixes worth scanning for the banner. Stainless emits
# code in many languages but the banner shape is language-agnostic.
_SOURCE_SUFFIXES: frozenset[str] = frozenset({
    ".py", ".ts", ".tsx", ".js", ".mjs", ".cjs",
    ".go", ".java", ".kt", ".rb", ".cs", ".php",
})

# Cap how many lines per file we inspect — banner is always at the top.
_BANNER_SEARCH_LINES = 8


def _file_has_banner(path: Path) -> tuple[bool, int | None, str]:
    """Return (banner_present, line_number, matched_text)."""
    try:
        with path.open("r", encoding="utf-8", errors="replace") as fh:
            head = []
            for i, line in enumerate(fh):
                if i >= _BANNER_SEARCH_LINES:
                    break
                head.append(line)
    except OSError:
        return False, None, ""
    blob = "".join(head)
    m = _BANNER_RE.search(blob)
    if not m:
        return False, None, ""
    line_no = blob[: m.start()].count("\n") + 1
    return True, line_no, m.group(0)


def _config_present(project_root: Path) -> tuple[bool, str]:
    """Return (any_config_present, relative_path_of_first_match)."""
    for name in _CONFIG_FILE_CANDIDATES:
        p = project_root / name
        if p.is_file():
            return True, name
    for d in _CONFIG_DIR_CANDIDATES:
        p = project_root / d
        if p.is_dir():
            return True, d + "/"
    return False, ""


def scan(project_root: Path) -> tuple[list[Finding], set[str]]:
    findings: list[Finding] = []
    scanned: set[str] = set()
    skip_dirs = {".git", "node_modules", "dist", "build", ".venv", "venv", "__pycache__"}

    # Arm 1: config-as-code presence — single config-level finding.
    has_config, config_rel = _config_present(project_root)
    if has_config:
        scanned.add(config_rel)
        findings.append(Finding(
            rule_id="AAK-MCP-LINEAGE-STAINLESS-001",
            title="Stainless generator-config present in project root",
            description=(
                "Found `" + config_rel + "` — a Stainless config-as-code "
                "file/directory. The source tree is therefore a Stainless-"
                "generated SDK / CLI / MCP-server. Provenance only; not a "
                "vulnerability. Useful for supply-chain attestation."
            ),
            severity=Severity.INFO,
            category=Category.SUPPLY_CHAIN,
            file_path=config_rel,
            evidence=(
                f"Stainless config-as-code marker present: `{config_rel}`. "
                f"Anchor: anthropic.com/news/anthropic-acquires-stainless (2026-05-18)."
            ),
            remediation=(
                "No action required for the rule fire itself — this is a "
                "lineage data point. For SBOM / supply-chain attestation, "
                "record the Stainless lineage alongside the package's own "
                "version metadata. If a future CVE targets a specific "
                "Stainless generator version, AAK will re-target this rule "
                "to fire on the affected lineage."
            ),
            incident_references=["ANTHROPIC-STAINLESS-2026-05-18"],
        ))

    # Arm 2: in-file banner detection — fires once per source file (capped
    # at 200 files per scan to bound runtime).
    banner_fires = 0
    for path in project_root.rglob("*"):
        if banner_fires >= 200:
            break
        if not path.is_file():
            continue
        if any(part in skip_dirs for part in path.parts):
            continue
        if path.suffix not in _SOURCE_SUFFIXES:
            continue
        has_banner, line_no, matched = _file_has_banner(path)
        if not has_banner:
            continue
        rel = str(path.relative_to(project_root))
        scanned.add(rel)
        banner_fires += 1
        findings.append(Finding(
            rule_id="AAK-MCP-LINEAGE-STAINLESS-001",
            title="Stainless-generator banner in source file",
            description=(
                "Source file carries a Stainless auto-generation banner "
                "(`" + matched + "`). The file is therefore generator-"
                "produced. Provenance only; not a vulnerability."
            ),
            severity=Severity.INFO,
            category=Category.SUPPLY_CHAIN,
            file_path=rel,
            line_number=line_no,
            evidence=f"banner: {matched!r}",
            remediation=(
                "No action required. Record the Stainless lineage in your "
                "SBOM if procurement reviewers ask for generator-origin "
                "metadata. Anchor: anthropic.com/news/anthropic-acquires-"
                "stainless (2026-05-18)."
            ),
            incident_references=["ANTHROPIC-STAINLESS-2026-05-18"],
        ))
    return findings, scanned


__all__ = ["scan"]
