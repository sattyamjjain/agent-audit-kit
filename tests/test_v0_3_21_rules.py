"""v0.3.21 — AAK-MCP-LINEAGE-STAINLESS-001 (Stainless-generator provenance).

Anchor: Anthropic acquired Stainless on 2026-05-18
(https://www.anthropic.com/news/anthropic-acquires-stainless).
Banner pattern verified verbatim against
github.com/anthropics/anthropic-sdk-python on 2026-05-19.

INFO severity — provenance only, not a vulnerability claim.
"""
from __future__ import annotations

import shutil
from pathlib import Path

from agent_audit_kit.scanners.stainless_lineage import scan as lineage_scan

FIXTURES = Path(__file__).parent / "fixtures" / "stainless_lineage"
RULE = "AAK-MCP-LINEAGE-STAINLESS-001"


def test_python_stainless_banner_fires(tmp_path: Path) -> None:
    """`# File generated from our OpenAPI spec by Stainless.` banner fires INFO."""
    shutil.copy(
        FIXTURES / "generated_python_sdk" / "client.py",
        tmp_path / "client.py",
    )
    findings, _ = lineage_scan(tmp_path)
    fires = [f for f in findings if f.rule_id == RULE]
    assert len(fires) == 1
    assert fires[0].severity.name == "INFO"
    assert "Stainless" in fires[0].evidence


def test_typescript_stainless_banner_fires(tmp_path: Path) -> None:
    """`// Code generated by Stainless.` short-form banner fires."""
    shutil.copy(
        FIXTURES / "generated_typescript_sdk" / "client.ts",
        tmp_path / "client.ts",
    )
    findings, _ = lineage_scan(tmp_path)
    fires = [f for f in findings if f.rule_id == RULE]
    assert len(fires) == 1
    assert "Stainless" in fires[0].evidence


def test_handwritten_source_passes(tmp_path: Path) -> None:
    """A hand-authored file with no banner must not fire."""
    shutil.copy(
        FIXTURES / "handwritten" / "server.py",
        tmp_path / "server.py",
    )
    findings, _ = lineage_scan(tmp_path)
    assert not any(f.rule_id == RULE for f in findings)


def test_stainless_yml_at_root_fires(tmp_path: Path) -> None:
    """`stainless.yml` at the project root fires the config-arm of the rule."""
    shutil.copy(
        FIXTURES / "config_root" / "stainless.yml",
        tmp_path / "stainless.yml",
    )
    findings, _ = lineage_scan(tmp_path)
    fires = [f for f in findings if f.rule_id == RULE]
    assert len(fires) == 1
    assert "stainless.yml" in fires[0].evidence


def test_empty_project_no_fires(tmp_path: Path) -> None:
    findings, _ = lineage_scan(tmp_path)
    assert findings == []


def test_banner_in_python_with_config_fires_twice(tmp_path: Path) -> None:
    """A project with both arms (banner file + config) fires the rule twice
    — once for the config, once for the source file."""
    shutil.copy(
        FIXTURES / "config_root" / "stainless.yml",
        tmp_path / "stainless.yml",
    )
    shutil.copy(
        FIXTURES / "generated_python_sdk" / "client.py",
        tmp_path / "client.py",
    )
    findings, _ = lineage_scan(tmp_path)
    fires = [f for f in findings if f.rule_id == RULE]
    assert len(fires) == 2
    file_paths = {f.file_path for f in fires}
    assert "stainless.yml" in file_paths
    assert "client.py" in file_paths
