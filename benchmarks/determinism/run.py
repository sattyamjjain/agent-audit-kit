#!/usr/bin/env python3
"""Determinism self-benchmark — proves AAK yields a byte-identical finding set.

Runs the **real AAK engine** (`agent_audit_kit.engine.run_scan`, the same
entrypoint the `scan` CLI drives) N=20 times over a fixed, committed corpus and
asserts every run produces the **same** finding set — one shared SHA-256 across
all 20 runs, i.e. 0% variance.

Why this matters: AAK's detection is deterministic rules over static input (no
model in the loop), so a re-run is verifiable. Tools that route findings through
an LLM judge cannot make that guarantee — see the cited contrast in
``RESULTS.md`` (scope-cited, **not** re-run here; no fabricated competitor
number).

Offline, no network, no LLM, no account. Run:

    python benchmarks/determinism/run.py            # print the report
    python benchmarks/determinism/run.py --write     # (re)write RESULTS.md
"""

from __future__ import annotations

import argparse
import hashlib
import json
import shutil
import tempfile
import time
from pathlib import Path

from agent_audit_kit.engine import run_scan

RUNS = 20
_HERE = Path(__file__).resolve().parent
_REPO = _HERE.parents[1]
RESULTS_MD = _HERE / "RESULTS.md"

# Fixed, committed corpus: the benchmark sample configs + two committed test
# fixtures. Every path is in-tree so the run is reproducible by anyone.
_CORPUS_SOURCES: tuple[Path, ...] = (
    _REPO / "benchmarks" / "sample_configs",
    _REPO / "tests" / "fixtures" / "clean_mcp.json",
    _REPO / "tests" / "fixtures" / "clean_settings.json",
)


def build_corpus(dest: Path) -> int:
    """Copy the fixed corpus into ``dest`` (one flat dir). Returns file count.

    The corpus is copied **once** and every one of the N runs scans the same
    directory, so the test isolates *engine* determinism (not tempdir naming).
    """
    n = 0
    for src in _CORPUS_SOURCES:
        files = sorted(src.rglob("*.json")) if src.is_dir() else [src]
        for f in files:
            if not f.is_file():
                continue
            # Unique, stable name so nothing collides and paths are fixed.
            rel = f.relative_to(_REPO).as_posix().replace("/", "__")
            shutil.copy(f, dest / rel)
            n += 1
    return n


def _finding_digest(result: object) -> str:
    """Canonical SHA-256 of a scan's finding set — order-independent.

    Only the stable identity fields are hashed (rule_id, file, line, severity,
    evidence); the list is sorted so scanner/registry iteration order cannot
    affect the digest.
    """
    rows = sorted(
        [
            f.rule_id,
            f.file_path,
            str(f.line_number),
            f.severity.value,
            f.evidence,
        ]
        for f in result.findings  # type: ignore[attr-defined]
    )
    blob = json.dumps(rows, sort_keys=True, ensure_ascii=False)
    return hashlib.sha256(blob.encode("utf-8")).hexdigest()


def run_benchmark(runs: int = RUNS) -> dict:
    """Scan the fixed corpus ``runs`` times; report the digest invariant.

    Returns a dict with corpus_size, findings, the shared digest, the number of
    *distinct* digests (1 == deterministic), and total wall-clock seconds.
    """
    tmp = Path(tempfile.mkdtemp(prefix="aak-determinism-"))
    try:
        corpus_size = build_corpus(tmp)
        digests: list[str] = []
        findings_count = 0
        start = time.perf_counter()
        for _ in range(runs):
            result = run_scan(tmp)
            findings_count = len(result.findings)
            digests.append(_finding_digest(result))
        elapsed = time.perf_counter() - start
    finally:
        shutil.rmtree(tmp, ignore_errors=True)

    unique = sorted(set(digests))
    return {
        "runs": runs,
        "corpus_size": corpus_size,
        "findings": findings_count,
        "digest": unique[0] if len(unique) == 1 else "",
        "distinct_digests": len(unique),
        "wall_clock_s": elapsed,
    }


def render_results_md(data: dict) -> str:
    from agent_audit_kit import RULE_COUNT, __version__

    deterministic = data["distinct_digests"] == 1
    verdict = (
        f"**{data['runs']}/{data['runs']} runs → 1 finding-set digest · 0% variance.**"
        if deterministic
        else f"**NON-DETERMINISTIC: {data['distinct_digests']} distinct digests across "
        f"{data['runs']} runs.**"
    )
    # Round wall-clock to a coarse bucket — timing is the only field that is not
    # reproducible across machines; the digest is the invariant that is.
    ms = int(round(data["wall_clock_s"] * 1000))
    return "\n".join([
        "# Determinism benchmark — AgentAuditKit",
        "",
        f"> Generated by `benchmarks/determinism/run.py` on AAK "
        f"v{__version__} ({RULE_COUNT} rules). Offline, no network, no LLM, no "
        "account. Reproduce: `python benchmarks/determinism/run.py`.",
        "",
        "## Result",
        "",
        verdict,
        "",
        "| Metric | Value |",
        "| --- | --- |",
        f"| Runs | {data['runs']} |",
        f"| Corpus (committed configs) | {data['corpus_size']} files |",
        f"| Findings per run | {data['findings']} |",
        f"| Distinct finding-set digests | **{data['distinct_digests']}** |",
        f"| Shared SHA-256 (finding set) | `{data['digest']}` |",
        f"| Total wall-clock, {data['runs']} runs | ≈ {ms} ms *(indicative — the "
        "only environment-dependent figure; the digest is the reproducible "
        "invariant)* |",
        "",
        "The corpus is `benchmarks/sample_configs/` plus two committed "
        "`tests/fixtures/` configs — every input is in-tree, so anyone can "
        "reproduce the exact digest. The engine is the same "
        "`agent_audit_kit.engine.run_scan` the `scan` CLI drives; detection is "
        "deterministic rules over static input, with no model in the loop.",
        "",
        "## Contrast (cited, not re-run)",
        "",
        "This is a self-benchmark of AAK. The tools below are **scope-cited from "
        "their own public docs — not re-run here**, and no competitor number is "
        "fabricated. The point is architectural: an LLM judge in the finding "
        "path forfeits the byte-identical-re-run guarantee above.",
        "",
        "- **Cisco DefenseClaw** (open-source, Apache-2.0) — its own docs "
        "describe runtime guardrails that inspect prompts/completions/tool calls "
        "with *“regex rules, policy, optional **LLM judge**”* and a Skill "
        "Scanner combining pattern rules with *LLM-as-a-judge* "
        "([cisco-ai-defense/defenseclaw](https://github.com/cisco-ai-defense/defenseclaw), "
        "[docs](https://cisco-ai-defense.github.io/docs/defenseclaw)).",
        "- **Snyk Agent Scan** — LLM-assisted analysis (per Snyk's product "
        "materials; the static-rule count is shown as `~30` in the comparison "
        "table above).",
        "",
        "LLM-as-judge evaluation is independently documented to vary run-to-run "
        "and to carry reliability/bias concerns — e.g. *“The Coin Flip Judge? "
        "Reliability and Bias in LLM-as-a-Judge Evaluation”* "
        "([arXiv:2606.13685](https://arxiv.org/abs/2606.13685)). We deliberately "
        "quote **no specific variance percentage** for the tools above: we did "
        "not re-run them, so any number would be invented. What we *can* prove is "
        "our own side — the table above, reproducible from this repo.",
        "",
    ])


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--write", action="store_true", help="(Re)write RESULTS.md.")
    ap.add_argument("--runs", type=int, default=RUNS, help="Number of runs (default 20).")
    args = ap.parse_args()

    data = run_benchmark(runs=args.runs)
    md = render_results_md(data)
    if args.write:
        RESULTS_MD.write_text(md.rstrip() + "\n", encoding="utf-8")
        print(f"wrote {RESULTS_MD.relative_to(_REPO)}")
    else:
        print(md)

    if data["distinct_digests"] != 1:
        print(f"\nFAIL: {data['distinct_digests']} distinct digests — non-deterministic!")
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
