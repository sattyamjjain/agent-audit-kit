def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawTextHelpFormatter)
    parser.add_argument("rule_id", nargs="?", help="print this rule's page as it will be published")
    parser.add_argument("--summary", action="store_true", help="counts, and rules no module names in code")
    args = parser.parse_args(argv)
    if not args.rule_id and not args.summary:
        parser.error("give a rule id or --summary")

    sys.path.insert(0, str(REPO_ROOT))
    rules, package_dir = default_registry()
    pages = build_pages(REPO_ROOT / "docs", rules, package_dir)

    if args.rule_id:
        uri = page_uri(args.rule_id)
        if uri not in pages:
            print(f"rule_pages: no such rule {args.rule_id!r}", file=sys.stderr)
            return 2
        sys.stdout.write(pages[uri])
        return 0

    mentions = named_in_code(package_dir, rules)
    own = own_pages(REPO_ROOT / "docs" / RULES_DIR, rules)
    silent = sorted(r for r in rules if r not in mentions)
    print(
        f"{len(rules)} rules: {len(own)} have a hand-written page (published verbatim, "
        f"registry reference appended), {len(rules) - len(own)} get a generated page."
    )
    print(f"{len(silent)} rules are named in code by no module (nothing known to emit them):")
    for rule_id in silent:
        print(f"  {rule_id}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
