#!/usr/bin/env python3
"""One help page behind every rule's SARIF "more info" link, generated at docs build time.

Why this exists
---------------
SARIF ``helpUri`` is the link GitHub's Security tab shows as "more info". Until
2026-09-05 it pointed at ``agent-audit-kit.dev``, which was never registered, so
every link was dead. The fix then was to point at the published docs site, but
only 13 of the 388 rules had a hand-written page under ``docs/rules/``. The rest
were sent to the rules index, which resolves and says nothing about the rule. A
frozen set of "rules that have a page" (``_rule_doc_pages.py``, regenerated by
``sync_rule_doc_pages.py``) kept the two apart, and it was a fact kept by hand in
a generated file's clothes.

This module removes the gap instead of describing it. Every rule in the registry
gets a page, rendered from the registry itself (title, severity, category,
description, remediation, limitations, every ``*_references`` field), so the page
cannot say something the scanner does not. The MkDocs hook in
``scripts/mkdocs_hooks.py`` adds the pages to the build, which means:

* **Nothing generated is committed.** There is no ``--check`` twin to run and
  none to forget. A rule added in a PR has a page the moment the docs are built.
* **Every helpUri resolves by construction**, because the page set *is* the
  registry. ``tests/test_rule_pages.py`` builds the site and proves it.

Which scanner emits a rule is read from the code, not written by hand
---------------------------------------------------------------------
``named_in_code`` parses every module under ``agent_audit_kit/`` (except the
registry, ``rules/``, which defines every id and so proves nothing) and records
which of them contain the rule id as a string literal. Comments and docstrings
are excluded on purpose: ``mcp_auth_patterns.py`` says in its docstring that it
"fires AAK-MCP-011..020" and emits seven of those ten, so a text search would
have credited it with AAK-MCP-016, -019 and -020, which no module emits. The
result is shown as found. A rule no module names in code says so ("no detector
in this release is known to emit it"), and ``--summary`` lists them.

The definition is deliberately literal, and the page says "Scanner", not
"guaranteed to fire": a scanner that built an id dynamically would be missed.
None does today (no module under ``agent_audit_kit/`` assembles an ``AAK-`` id
with an f-string), and the page states what the search saw rather than what it
hoped.

Hand-written pages stay authoritative
-------------------------------------
Some rules have a deep dive in ``docs/rules/<ID>.md``, and the published URL
``.../docs/rules/<ID>/`` is already in people's SARIF history. That URL cannot
move and that text cannot be replaced. So the hook publishes the hand-written
page *verbatim* and appends the registry-derived reference below it, under a
rule and a heading that says which part is which. Nothing above the divider is
touched, and the file on disk is never written to. ``docs/rules/skill-
composition.md`` covers several rules in one page; those rules link to the
heading that names them, found by reading the page's headings rather than by
listing them here.

Structure
---------
A generated page has one ``h1`` (``AAK-MCP-003: <title>``, the words the browser
tab shows too), a description list of facts, and a fixed set of ``h2`` sections:
What it detects, How to fix, Limitations, References, plus Deep dive when the rule
is written up inside a page shared with other rules. Two choices there are
accessibility fixes, not taste:

* The facts are a description list (``dt``/``dd``), not a ``Field | Value`` table.
  A Markdown table has no row headers, so a screen reader read "HIGH" without
  saying which fact it was. The list needs the ``def_list`` extension, which
  ``mkdocs.yml`` enables and ``tests/test_rule_pages.py`` insists on.
* The title is in the ``h1``, so the heading list says what the page is about
  and not only which rule it is.

Hand-written pages get the same ``title:`` front matter when they have none
(MkDocs strips it before rendering, so their text is still published unchanged);
without it the browser tab said only ``AAK-AZURE-MCP-001``.

Escaping
--------
Rule text is written as Markdown (it carries backticks, bold and links), so it is
rendered as Markdown, with five repairs for text written for a terminal and for
SARIF, where none of them mattered:

* ``<handle>@<psp>`` is not an HTML tag, but the renderer treats it as one and
  the words vanish, so ``<``, ``>`` and ``&`` are escaped outside code spans.
* ``(*.pem, *.key)`` and ``glpat-*`` are globs, but Python-Markdown pairs any two
  asterisks and prints italics with the asterisks eaten, so an asterisk that is
  not half of an emphasis pair is escaped (``stray_asterisks``).
* ``__route__`` is a word, not bold (``escape_dunders``).
* An indented list directly after a sentence is folded into the paragraph by
  Python-Markdown, so a blank line is put around list items.
* A line starting with ``#`` is a heading to Python-Markdown (no space needed, and
  after a list marker too), and a line of only dashes or equals signs under a
  line of text is a Setext underline. Rule text with either would add headings to
  the page's outline, so the ``#`` is escaped and the underline is broken up
  (``neutralize_headings``). Fenced code is left alone.

Code spans, and the asterisks and underscores scanning above, are found by
walking the string, not with a regex: the text is short, but a pattern with nested
quantifiers over registry strings is exactly what a ReDoS alert is made of.

Usage:
    python scripts/rule_pages.py AAK-MCP-003     # print the page as it will be published
    python scripts/rule_pages.py --summary       # counts, plus rules no module names in code
"""

