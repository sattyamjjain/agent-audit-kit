def split_code_spans(text: str) -> list[tuple[bool, str]]:
    """Split ``text`` into (is_code, chunk) pieces on CommonMark code spans.

    A span opens on a run of N backticks and closes on the next run of exactly N.
    A run with no matching closer is literal text. Scanning rather than a regex:
    see the module docstring.
    """
    parts: list[tuple[bool, str]] = []
    size = len(text)
    start = 0  # start of the pending plain chunk
    i = 0
    while i < size:
        if text[i] != "`":
            i += 1
            continue
        j = i
        while j < size and text[j] == "`":
            j += 1
        width = j - i
        close = -1
        k = j
        while k < size:
            if text[k] != "`":
                k += 1
                continue
            m = k
            while m < size and text[m] == "`":
                m += 1
            if m - k == width:
                close = k
                break
            k = m
        if close == -1:
            i = j
            continue
        if i > start:
            parts.append((False, text[start:i]))
        parts.append((True, text[i : close + width]))
        i = start = close + width
    if start < size:
        parts.append((False, text[start:]))
    return parts


#: What may stand before an asterisk that opens emphasis, what may stand before
#: one that closes it (besides a letter or digit), and what may follow a closer.
#: Deliberately narrower than CommonMark's flanking rules: a glob such as
#: ``ghp_*, glpat-*`` is flanked by punctuation on both sides, which CommonMark
#: reads as a valid pair.
_BEFORE_OPENER = frozenset(" \t\n\r([{\"'“‘—:;,")
_BEFORE_CLOSER = frozenset(".!?)]}\"'”’:;,")
_AFTER_CLOSER = frozenset(" \t\n\r.,;:!?)]}\"'”’—")


def stray_asterisks(masked: str) -> set[int]:
    """Positions of ``*`` characters in ``masked`` that are not half of an emphasis pair.

    Rule text is Markdown (``**bold**``, ``*emphasis*``) but also names globs in
    prose: ``(*.pem, *.key)``, ``X-*-Key``, ``glpat-*``. Python-Markdown pairs any
    two asterisks it can, so those render as italics with the asterisks eaten
    (``<em>.pem, </em>.key``), in the places a reader most needs the literal
    pattern. An asterisk run is kept as markup only when it is shaped like
    emphasis and a matching run closes it; every other one is returned to be
    escaped.

    ``masked`` is the text with each code span replaced by letters, so an
    asterisk inside a span is invisible here and emphasis around a span still
    pairs. A run directly after a backslash was escaped by its author, and a lone
    ``*`` opening a line followed by a space is a list marker; both are left
    alone, and neither is returned.
    """
    size = len(masked)
    runs: list[tuple[int, int]] = []
    i = 0
    while i < size:
        if masked[i] != "*":
            i += 1
            continue
        j = i
        while j < size and masked[j] == "*":
            j += 1
        runs.append((i, j))
        i = j

    paired: set[int] = set()
    leave: set[int] = set()
    stack: list[tuple[int, int]] = []  # (run index, width) of unmatched openers
    for index, (start, end) in enumerate(runs):
        width = end - start
        before = masked[start - 1] if start else " "
        after = masked[end] if end < size else " "
        line_start = masked.rfind("\n", 0, start) + 1
        if before == "\\" or (
            width == 1 and after in {" ", "\t"} and not masked[line_start:start].strip()
        ):
            leave.add(index)
            continue
        if width > 2:
            continue
        can_close = (before.isalnum() or before in _BEFORE_CLOSER) and after in _AFTER_CLOSER
        can_open = after.isalnum() and before in _BEFORE_OPENER
        matched = False
        if can_close:
            for depth in range(len(stack) - 1, -1, -1):
                if stack[depth][1] == width:
                    paired.update((index, stack[depth][0]))
                    del stack[depth:]
                    matched = True
                    break
        if not matched and can_open:
            stack.append((index, width))
    return {
        position
        for index, (start, end) in enumerate(runs)
        if index not in paired and index not in leave
        for position in range(start, end)
    }


def escape_dunders(text: str) -> str:
    """Backslash-escape ``__name__`` words so they are not read as bold.

    ``__route__=`` in prose renders as **route**=, because a double underscore
    at a word boundary is strong emphasis. Dunder names (``__init__``,
    ``__import__``, ``__class__``) turn up in the text of Python rules, and
    usually unquoted. Only a word that starts and ends with ``__`` is touched, so
    ``snake_case`` and ``a__b`` are left alone. A manual scan, not a regex, for
    the same reason as ``split_code_spans``.
    """
    out: list[str] = []
    size = len(text)
    i = 0
    while i < size:
        starts_word = i == 0 or not (text[i - 1].isalnum() or text[i - 1] in "_\\")
        if starts_word and text.startswith("__", i):
            j = i + 2
            while j < size and (text[j].isalnum() or text[j] == "_"):
                j += 1
            word = text[i + 2 : j]
            if len(word) > 2 and word.endswith("__") and word[0] != "_":
                out.append("\\_\\_" + word[:-2] + "\\_\\_")
                i = j
                continue
        out.append(text[i])
        i += 1
    return "".join(out)


def escape_markdown(text: str) -> str:
    """Make registry text safe for a page, leaving code spans and real emphasis alone.

    Outside code spans: ``<``, ``>`` and ``&`` are escaped (so ``<handle>`` is
    text, not a tag the renderer swallows), an asterisk that is not half of an
    emphasis pair is backslash-escaped (``stray_asterisks``), and ``__name__``
    words are kept from turning bold (``escape_dunders``).
    """
    parts = split_code_spans(text)
    masked = "".join("a" * len(chunk) if is_code else chunk for is_code, chunk in parts)
    stray = stray_asterisks(masked)
    out: list[str] = []
    offset = 0
    for is_code, chunk in parts:
        if is_code:
            out.append(chunk)
        else:
            marked = "".join(
                "\\*" if offset + index in stray else char for index, char in enumerate(chunk)
            )
            out.append(html.escape(escape_dunders(marked), quote=False))
        offset += len(chunk)
    return "".join(out)


_LIST_ITEM_RE = re.compile(r" {0,3}(?:[-*+]|\d{1,9}[.)])[ \t]+\S")


def separate_lists(text: str) -> str:
    """Put a blank line before and after every list, so the renderer sees a list.

    Python-Markdown (unlike CommonMark) does not let a list interrupt a
    paragraph: ``"as follows:\\n  - one\\n  - two\\nAnd then"`` renders as one run
    of text with literal hyphens. Rule text was written for a terminal and for
    SARIF, where that is fine, and one description (AAK-MCP-LETTA-CVE-2025-
    51482-001) is such a list.
    """
    out: list[str] = []
    previous = "blank"
    for line in text.split("\n"):
        if not line.strip():
            kind = "blank"
        elif _LIST_ITEM_RE.match(line):
            kind = "item"
        elif previous in {"item", "continuation"} and line[:1] in {" ", "\t"}:
            kind = "continuation"
        else:
            kind = "text"
        if kind == "item" and previous == "text":
            out.append("")
        elif kind == "text" and previous in {"item", "continuation"}:
            out.append("")
        out.append(line)
        previous = kind
    return "\n".join(out)


def _marker_end(line: str, start: int) -> int:
    """Index just past a list marker and the blanks after it, or ``start`` if none is there."""
    size = len(line)
    end = start
    if end < size and line[end] in "-*+":
        end += 1
    else:
        while end < size and end - start < 9 and line[end].isdigit():
            end += 1
        if end == start or end >= size or line[end] not in ".)":
            return start
        end += 1
    if end >= size or line[end] not in " \t":
        return start
    while end < size and line[end] in " \t":
        end += 1
    return end


def _text_start(line: str) -> int:
    """Index of the first character of a line's own text, past indentation and list markers.

    ``- # x`` and ``1. # x`` are headings inside a list item to Python-Markdown, so
    the character that matters is the one after the markers, not the first one.
    """
    start = 0
    while True:
        while start < len(line) and line[start] in " \t":
            start += 1
        after = _marker_end(line, start)
        if after == start:
            return start
        start = after


def _fence_run(stripped: str) -> str:
    """The run of backticks or tildes that opens or closes a code fence on this line, else ``""``.

    A backtick run followed by more backticks is an inline code span that happens
    to start the line, which is text and not a fence.
    """
    if not stripped or stripped[0] not in "`~":
        return ""
    width = 1
    while width < len(stripped) and stripped[width] == stripped[0]:
        width += 1
    if width < 3 or (stripped[0] == "`" and "`" in stripped[width:]):
        return ""
    return stripped[:width]


def neutralize_headings(text: str) -> str:
    """Keep registry prose from adding headings to the page it is dropped into.

    Python-Markdown makes a heading of any line that starts with ``#`` (a space
    after it is optional, and a list marker before it does not stop it), and of a
    line of text followed by a line of only ``-`` or ``=`` (a Setext underline).
    Registry text has neither today, but it is free text that two contributors
    edit, and a stray ``# comment`` line would put an extra ``h1`` into every
    reader's heading list, which is how a screen reader user finds their way
    around. So a leading ``#`` is backslash-escaped, and an underline that follows
    text has its first character escaped (``\\-``, or the entity ``&#61;`` for
    ``=``, because Python-Markdown does not treat ``\\=`` as an escape and would
    print the backslash).

    Fenced code blocks are skipped: a ``# comment`` there is code, and an escape
    would show up in it. A fence that is never closed is not a fence to the
    renderer either, so what follows it is treated as text. Indented code blocks
    are not recognised, so registry text that needs a literal block must fence it.
    """
    lines = text.split("\n")
    out: list[str] = []
    follows_text = False
    index = 0
    while index < len(lines):
        line = lines[index]
        stripped = line.strip()
        run = _fence_run(stripped)
        closer = next(
            (
                later
                for later in range(index + 1, len(lines))
                if run and set(lines[later].strip()) == {run[0]} and len(lines[later].strip()) >= len(run)
            ),
            None,
        )
        if closer is not None:
            out.extend(lines[index : closer + 1])
            follows_text = False
            index = closer + 1
            continue
        start = _text_start(line)
        if line[start:].startswith("#"):
            line = line[:start] + "\\" + line[start:]
        elif follows_text and stripped and (set(stripped) == {"-"} or set(stripped) == {"="}):
            first = len(line) - len(line.lstrip())
            escaped = "\\-" if stripped[0] == "-" else "&#61;"
            line = line[:first] + escaped + line[first + 1 :]
        out.append(line)
        follows_text = bool(stripped)
        index += 1
    return "\n".join(out)


def heading_text(title: str) -> str:
    """A rule title as the text of a one-line ATX heading, markup kept.

    A heading line may end in a closing run of ``#`` which the renderer drops, so
    a title that ends in ``#`` would lose it; each trailing ``#`` is escaped.
    Whitespace is collapsed so a title with a newline in it cannot end the heading
    early.
    """
    line = " ".join(escape_markdown(title).split())
    bare = line.rstrip("#")
    return bare + "\\#" * (len(line) - len(bare))


def markdown_text(text: str) -> str:
    """Registry prose, made safe to drop into a page body."""
    return neutralize_headings(escape_markdown(separate_lists(text.strip())))


def plain_text(text: str) -> str:
    """Registry prose with its inline markup flattened, for a title or a meta tag."""
    flat = _LINK_RE.sub(r"\1", text).replace("`", "").replace("**", "")
    return " ".join(flat.split())


def _table_cell(text: str) -> str:
    """Make ``text`` safe inside a one-line table cell."""
    return " ".join(text.split()).replace("|", "\\|")


def _json_string(text: str) -> str:
    """A YAML double-quoted scalar. JSON string syntax is a subset of YAML's."""
    return json.dumps(text, ensure_ascii=False)


