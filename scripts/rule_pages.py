#: Where each reference field is shown, in reading order, and under what name.
#: A ``*_references`` field on RuleDefinition that is missing here is still
#: rendered (see ``reference_fields``), under a name derived from the field, so a
#: new framework added to the registry shows up in 388 pages without an edit here.
REFERENCE_LABELS: dict[str, str] = {
    "cve_references": "CVE",
    "owasp_mcp_references": "OWASP MCP Top 10",
    "owasp_agentic_references": "OWASP Agentic Top 10",
    "owasp_ast_references": "OWASP Agentic Skills Top 10",
    "adversa_references": "Adversa AI MCP Top 25 (AAK-defined ids)",
    "incident_references": "Incidents and advisories",
    "aicm_references": "CSA AI Controls Matrix (AICM)",
}

#: The framework's own page, where one exists and was verified to resolve.
#: Adversa's ids are AAK-defined (see CLAUDE.md), so there is no page to send a
#: reader to.
_LABEL_LINKS: dict[str, str] = {
    "owasp_mcp_references": "https://github.com/OWASP/www-project-mcp-top-10",
    "owasp_agentic_references": (
        "https://genai.owasp.org/resource/owasp-top-10-for-agentic-applications-for-2026/"
    ),
    "owasp_ast_references": "https://github.com/OWASP/www-project-agentic-skills-top-10",
    "aicm_references": "https://cloudsecurityalliance.org/artifacts/ai-controls-matrix",
}

#: Field -> name of the id->title table in ``agent_audit_kit.output.owasp_report``.
_NAME_TABLES: dict[str, str] = {
    "owasp_mcp_references": "OWASP_MCP",
    "owasp_agentic_references": "OWASP_AGENTIC",
    "owasp_ast_references": "OWASP_AST",
    "adversa_references": "ADVERSA_TOP_25",
}

#: Reference formats with one canonical, stable public page. Anything else (an
#: internal incident slug, a vendor blog) is shown as text rather than linked to
#: a URL this module would have to guess. ``fullmatch`` against each pattern.
_REFERENCE_URLS: tuple[tuple[re.Pattern[str], str], ...] = (
    (re.compile(r"CVE-\d{4}-\d{4,}"), "https://nvd.nist.gov/vuln/detail/{0}"),
    (re.compile(r"GHSA(?:-[a-z0-9]{4}){3}"), "https://github.com/advisories/{0}"),
    (re.compile(r"(?i:arxiv)[-:](\d{4}\.\d{4,5}(?:v\d+)?)"), "https://arxiv.org/abs/{1}"),
    (re.compile(r"CERT-CC-VU-(\d+)"), "https://www.kb.cert.org/vuls/id/{1}"),
    (re.compile(r"VULDB-(\d+)"), "https://vuldb.com/?id.{1}"),
    # A bare host and path, as in `platform.claude.com/docs/...`.
    (re.compile(r"[a-z0-9-]+(?:\.[a-z0-9-]+)+/\S+"), "https://{0}"),
)


def reference_url(value: str) -> str | None:
    """The public URL for a reference id, when its format has a canonical one."""
    for pattern, template in _REFERENCE_URLS:
        match = pattern.fullmatch(value)
        if match:
            return template.format(value, *match.groups())
    return None


def reference_fields(rule_type: type) -> list[str]:
    """Every ``*_references`` field of a rule class, known ones first in reading order."""
    present = [f.name for f in dataclasses.fields(rule_type) if f.name.endswith("_references")]
    known = [name for name in REFERENCE_LABELS if name in present]
    return known + [name for name in present if name not in REFERENCE_LABELS]


def _reference_label(field_name: str) -> str:
    if field_name in REFERENCE_LABELS:
        return REFERENCE_LABELS[field_name]
    return field_name[: -len("_references")].replace("_", " ").title()


def _name_tables() -> dict[str, Mapping[str, str]]:
    """The id->title tables the console OWASP report already uses.

    Read with ``getattr`` so a renamed or restructured table degrades a page to
    ids-only instead of failing the whole docs build: the titles are a courtesy,
    the ids are the data.
    """
    try:
        from agent_audit_kit.output import owasp_report
    except ImportError:  # pragma: no cover - the package is importable wherever the registry is
        return {}
    return {
        field_name: getattr(owasp_report, table, {}) for field_name, table in _NAME_TABLES.items()
    }


def render_references(rule: Any, names: Mapping[str, Mapping[str, str]] | None = None) -> list[str]:
    """One Markdown bullet per non-empty reference field."""
    tables = _name_tables() if names is None else names
    lines: list[str] = []
    for field_name in reference_fields(type(rule)):
        values = list(getattr(rule, field_name, []) or [])
        if not values:
            continue
        label = _reference_label(field_name)
        if field_name in _LABEL_LINKS:
            label = f"[{label}]({_LABEL_LINKS[field_name]})"
        titles = tables.get(field_name, {})
        items: list[str] = []
        for value in values:
            shown = escape_markdown(value)
            url = reference_url(value)
            item = f"[{shown}]({url})" if url else shown
            if value in titles:
                item += f" ({escape_markdown(titles[value])})"
            items.append(item)
        lines.append(f"- **{label}:** {', '.join(items)}")
    return lines


