_RULE_ID_TOKEN_RE = re.compile(r"AAK-[A-Z0-9]+(?:-[A-Z0-9]+)*")
_LINK_RE = re.compile(r"\[([^\]]*)\]\([^)]*\)")


def own_pages(rules_dir: Path, rule_ids: Iterable[str]) -> dict[str, str]:
    """Rule id -> text of its hand-written page, for every ``docs/rules/<ID>.md``.

    Read, never written. A page whose stem is not a registered rule id (the
    index, a page shared by several rules, a misspelt filename) is not a rule's
    own page; ``tests/test_rule_pages.py`` catches the misspelling.
    """
    wanted = set(rule_ids)
    if not rules_dir.is_dir():
        return {}
    return {
        path.stem: path.read_text(encoding="utf-8")
        for path in sorted(rules_dir.glob("*.md"))
        if path.stem in wanted
    }


def slugify(heading: str) -> str:
    """The anchor Python-Markdown's ``toc`` extension gives a heading.

    Mirrors ``markdown.extensions.toc.slugify`` after the inline markup is
    reduced to its text: backticks, link syntax and emphasis markers do not
    reach the id. ``tests/test_rule_pages.py`` compares it against the real
    extension, so a change there is caught rather than assumed away.
    """
    text = _LINK_RE.sub(r"\1", heading)
    text = text.replace("`", "").replace("*", "")
    text = unicodedata.normalize("NFKD", text).encode("ascii", "ignore").decode("ascii")
    text = re.sub(r"[^\w\s-]", "", text).strip().lower()
    return re.sub(r"[-\s]+", "-", text)


def _headings(text: str) -> list[tuple[int, str]]:
    """(level, heading text) for every ATX heading outside a fenced code block."""
    out: list[tuple[int, str]] = []
    fenced = False
    for line in text.splitlines():
        stripped = line.strip()
        if stripped.startswith(("```", "~~~")):
            fenced = not fenced
            continue
        if fenced or not line.startswith("#"):
            continue
        level = len(line) - len(line.lstrip("#"))
        if level > 6 or line[level : level + 1] not in {" ", "\t"}:
            continue
        out.append((level, line[level:].strip().rstrip("#").strip()))
    return out


def shared_deep_dives(rules_dir: Path, rule_ids: Iterable[str]) -> dict[str, tuple[str, str, str]]:
    """Rule id -> (page stem, page title, anchor) for rules covered inside a shared page.

    ``docs/rules/skill-composition.md`` documents several rules in one page. The
    page is found, and the section for each rule is found, by reading headings:
    a heading that *starts with* a rule id is that rule's section, and failing
    that the first heading that merely names it. Pages named for a single rule
    and the index are skipped, so one hand-written page cannot adopt another
    rule just by mentioning it in a "sister rule" heading.
    """
    wanted = set(rule_ids)
    found: dict[str, tuple[str, str, str]] = {}
    if not rules_dir.is_dir():
        return found
    for path in sorted(rules_dir.glob("*.md")):
        if path.stem in wanted or path.stem == "index":
            continue
        headings = _headings(path.read_text(encoding="utf-8"))
        title = next((text for level, text in headings if level == 1), path.stem)
        title = _LINK_RE.sub(r"\1", title).replace("`", "")
        first: dict[str, str] = {}
        primary: dict[str, str] = {}
        for _level, text in headings:
            bare = text.replace("`", "")
            for token in _RULE_ID_TOKEN_RE.findall(bare):
                if token not in wanted:
                    continue
                first.setdefault(token, text)
                if bare.startswith(token):
                    primary.setdefault(token, text)
        for token, text in {**first, **primary}.items():
            found.setdefault(token, (path.stem, title, slugify(text)))
    return found


