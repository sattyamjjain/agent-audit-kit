def page_uri(rule_id: str) -> str:
    """Path of a rule's page relative to the docs directory."""
    return f"{RULES_DIR}/{rule_id}.md"


def default_registry() -> tuple[Mapping[str, Any], Path]:
    """The live registry, and the directory of the package it was imported from.

    The package directory comes from the imported module rather than from this
    file's location, so the registry we render and the source we search can never
    be two different trees (an editable install pointing at another checkout is a
    known way to get that wrong).
    """
    import agent_audit_kit
    from agent_audit_kit.rules.builtin import RULES

    return RULES, Path(agent_audit_kit.__file__).resolve().parent


def build_pages(
    docs_dir: Path,
    rules: Mapping[str, Any] | None = None,
    package_dir: Path | None = None,
) -> dict[str, str]:
    """Markdown for every page this module owns, keyed by docs-relative path.

    One entry per registered rule, plus ``rules/index.md`` (the hand-written
    index with the full listing appended). For a rule with a hand-written page
    the entry is that page plus the registry reference; the file on disk is only
    ever read.
    """
    if rules is None:
        rules = default_registry()[0]
    if package_dir is None:
        package_dir = default_registry()[1]

    rules_dir = docs_dir / RULES_DIR
    mentions = named_in_code(package_dir, rules)
    own = own_pages(rules_dir, rules)
    shared = shared_deep_dives(rules_dir, rules)
    display = category_names()
    names = _name_tables()

    pages: dict[str, str] = {}
    for rule_id in sorted(rules):
        scanners, elsewhere = split_scanners(mentions.get(rule_id, ()), package_dir.name)
        sources = Sources(scanners=scanners, elsewhere=elsewhere, shared=shared.get(rule_id))
        pages[page_uri(rule_id)] = render_page(
            rules[rule_id],
            sources,
            own.get(rule_id),
            category_display=display,
            names=names,
        )

    index = rules_dir / "index.md"
    intro = index.read_text(encoding="utf-8") if index.is_file() else "# Rule reference\n"
    pages[INDEX_URI] = (
        intro.rstrip("\n") + "\n\n" + render_index_listing(rules, display)
    )
    return pages


