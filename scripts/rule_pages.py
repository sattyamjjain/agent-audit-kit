def _code_literals(path: Path) -> set[str]:
    """Every string literal in ``path``'s code, docstrings and comments excluded.

    A docstring is a bare expression statement, so any ``ast.Expr`` wrapping a
    string is prose, including the string-after-assignment "attribute docstring"
    convention. Comments never reach the AST at all, which is the other half of
    why this is an AST walk and not ``grep``.
    """
    tree = ast.parse(path.read_text(encoding="utf-8"), filename=str(path))
    prose = {
        id(node.value)
        for node in ast.walk(tree)
        if isinstance(node, ast.Expr)
        and isinstance(node.value, ast.Constant)
        and isinstance(node.value.value, str)
    }
    return {
        node.value
        for node in ast.walk(tree)
        if isinstance(node, ast.Constant)
        and isinstance(node.value, str)
        and id(node) not in prose
    }


def named_in_code(package_dir: Path, rule_ids: Iterable[str]) -> dict[str, tuple[str, ...]]:
    """Map each rule id to the modules that contain it as a string literal in code.

    Paths are posix and start at the package directory's own name
    (``agent_audit_kit/scanners/mcp_config.py``), so they read as repository
    paths and can be appended to ``BLOB_BASE``. A rule absent from the result is
    named by no module at all.
    """
    wanted = set(rule_ids)
    found: dict[str, set[str]] = {}
    for path in sorted(package_dir.rglob("*.py")):
        relative = path.relative_to(package_dir)
        if relative.parts[0] == _REGISTRY_DIR:
            continue
        module = f"{package_dir.name}/{relative.as_posix()}"
        for literal in _code_literals(path) & wanted:
            found.setdefault(literal, set()).add(module)
    return {rule_id: tuple(sorted(modules)) for rule_id, modules in found.items()}


def split_scanners(modules: Iterable[str], package_name: str) -> tuple[tuple[str, ...], tuple[str, ...]]:
    """Partition module paths into (scanner modules, everything else)."""
    prefix = f"{package_name}/{SCANNER_DIR}/"
    scanners: list[str] = []
    elsewhere: list[str] = []
    for module in modules:
        (scanners if module.startswith(prefix) else elsewhere).append(module)
    return tuple(scanners), tuple(elsewhere)


